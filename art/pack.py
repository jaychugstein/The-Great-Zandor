# Packs the questions, the things and the answer table for the FX chip. Writes ../TheGreatZandor/fxdata.h and ../TheGreatZandor/fxdata/*.bin.
import os
from data import Q, OBJ, matrix
ART = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(ART, '..', 'TheGreatZandor')
M = matrix(); N, NQ = len(OBJ), len(Q); NAMELEN, QLEN = 24, 44
def txt(s, n):
    b = s.upper().encode('ascii'); assert len(b) < n, s; return b + bytes(n - len(b))
parts = []
parts.append(('MATQ', bytes(M[i][q] for q in range(NQ) for i in range(N)), 'answers by question: NOBJ bytes a question (0 no .. 4 yes)'))
parts.append(('CATS', bytes('AVMO'.index(c) | (max(0, min(4, (18 - sum(1 for v in M[i] if v >= 3)) // 3)) << 4) for i, (_, c, _, _) in enumerate(OBJ)), 'each thing\'s group (low 4 bits) and how sparse its answers are (high bits: a small head start taken off, so thin entries do not win by default)'))
parts.append(('NAMES', b''.join(txt(n, NAMELEN) for n, _, _, _ in OBJ), 'names, %d bytes each' % NAMELEN))
QW = [5 if k in ('green','red','yellow','orange','brown','black','white','colorful','cute','old','everyday','gift') else 8 for k, _ in Q]
parts.append(('QWT', bytes(QW), 'how much each question is favoured (8 = fully, less = saved for later)'))
parts.append(('QTEXT', b''.join(txt(t, QLEN) for _, t in Q), 'question text, %d bytes each' % QLEN))
from PIL import Image
z = Image.open(os.path.join(ART, 'zandor.png')).convert('1'); zw, zh = z.size; zp = z.load()
zb = bytes([zw >> 8, zw & 255, zh >> 8, zh & 255]) + bytes(sum((1 << b) for b in range(8) if zp[x, p * 8 + b]) for p in range(zh // 8) for x in range(zw))
parts.append(('ZANDOR', zb, 'the fortune teller, 48 x 64'))
data = bytearray(); hdr = []
for name, blob, note in parts:
    hdr.append('constexpr uint24_t %-6s = 0x%06X;   // %s' % (name, len(data), note)); data += blob
while len(data) % 4096: data.append(0xFF)
dpage = 0x10000 - (len(data) + 4096) // 256; spage = 0x10000 - 16
os.makedirs(os.path.join(OUT, 'fxdata'), exist_ok=True)
open(os.path.join(OUT, 'fxdata', 'fxdata.bin'), 'wb').write(data + b'\xff' * 4096)
h = '// generated by art/pack.py - do not edit\n#pragma once\n#include <ArduboyFX.h>\n'
h += 'constexpr uint16_t FX_DATA_PAGE = 0x%04X;\nconstexpr uint16_t FX_SAVE_PAGE = 0x%04X;\n' % (dpage, spage)
h += 'constexpr uint16_t NOBJ = %d, NQ = %d, NAMELEN = %d, QLEN = %d;\n' % (N, NQ, NAMELEN, QLEN) + '\n'.join(hdr) + '\n'
open(os.path.join(OUT, 'fxdata.h'), 'w').write(h); print(h)
